  function buildRaw(rawArray) {
    var out = [];
    for (var i = 0; i < rawArray.length; i++) {
      var item = rawArray[i];
      var hex = String(item[0]).toUpperCase();
      var rgb = safeRgb(hex);
      if (!rgb) continue;
      out.push({
        hex: hex,
        name: item[1],
        rgb: rgb,
        lab: rgbToOklab(rgb.r, rgb.g, rgb.b)
      });
    }
    return out;
  }

  var CN_PALETTE = buildRaw(CN_RAW);
  var MORANDI_PALETTE = buildRaw(MORANDI_RAW);
  var JP_PALETTE = buildRaw(JP_RAW);
  var CYBER_PALETTE = buildRaw(CYBER_RAW);

  var LIB_MAP = { cn: CN_PALETTE, jp: JP_PALETTE, morandi: MORANDI_PALETTE, cyber: CYBER_PALETTE };
  var CACHES = { cn: new Map(), jp: new Map(), morandi: new Map(), cyber: new Map() };

  function findNearestColor(rgb, palette, cache) {
    if (!rgb || !palette || !palette.length) return null;
    var key = rgb.r + ',' + rgb.g + ',' + rgb.b;
    if (cache.has(key)) return cache.get(key);

    var lab = rgbToOklab(rgb.r, rgb.g, rgb.b);
    var best = Infinity;
    var match = null;

    for (var i = 0; i < palette.length; i++) {
      var c = palette[i];
      var dL = lab.L - c.lab.L, da = lab.a - c.lab.a, db = lab.b - c.lab.b;
      var d = dL * dL + da * da + db * db;
      if (d < best) { best = d; match = c; }
    }

    if (match) cache.set(key, match);
    return match;
  }

  function toRgb(hexOrRgb) {
    if (!hexOrRgb) return null;
    if (typeof hexOrRgb === 'string') return safeRgb(hexOrRgb);
    if (typeof hexOrRgb.r === 'number') return hexOrRgb;
    return null;
  }

  function lookup(hexOrRgb, libKey) {
    var k = LIB_MAP[libKey] ? libKey : 'cn';
    return findNearestColor(toRgb(hexOrRgb), LIB_MAP[k], CACHES[k]);
  }

  function name(hexOrRgb, libKey) {
    var m = lookup(hexOrRgb, libKey);
    return m ? m.name : '—';
  }

